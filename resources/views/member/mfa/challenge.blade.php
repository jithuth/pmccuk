<script>
let isRecoveryMode = false;
function toggleRecoveryMode() {
    isRecoveryMode = !isRecoveryMode;
    const input = document.getElementById('mfa_code');
    const label = document.getElementById('code_label');
    const hint = document.getElementById('code_hint');
    const toggleBtn = document.getElementById('recoveryToggleBtn');

    if (isRecoveryMode) {
        label.innerText = 'Single-Use Recovery Code';
        input.placeholder = 'XXXX-XXXX';
        input.style.letterSpacing = '0.15em';
        input.value = '';
        hint.innerText = 'Enter one of your 8-character emergency backup recovery codes.';
        toggleBtn.innerHTML = '<i class="fa-solid fa-mobile-screen"></i> Use Authenticator App Code';
    } else {
        label.innerText = '6-Digit Passcode';
        input.placeholder = '••••••';
        input.style.letterSpacing = '0.4em';
        input.value = '';
        hint.innerText = 'Open Google Authenticator, Microsoft Authenticator, or 1Password.';
        toggleBtn.innerHTML = '<i class="fa-solid fa-key"></i> Use Recovery Code';
    }
    input.focus();
}
</script>
